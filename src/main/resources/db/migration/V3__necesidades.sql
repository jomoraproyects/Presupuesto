CREATE TABLE necesidad_presupuestal (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  vigencia_id BIGINT NOT NULL,
  area_id BIGINT NOT NULL,
  rubro_presupuestal_id BIGINT NOT NULL,
  descripcion VARCHAR(500) NOT NULL,
  justificacion VARCHAR(2000) NOT NULL,
  unidad_medida VARCHAR(60) NOT NULL,
  cantidad_solicitada DECIMAL(19,4) NOT NULL,
  valor_unitario_solicitado DECIMAL(19,2) NOT NULL,
  valor_total_solicitado DECIMAL(19,2) NOT NULL,
  cantidad_solicitada_original DECIMAL(19,4),
  valor_unitario_solicitado_original DECIMAL(19,2),
  valor_total_solicitado_original DECIMAL(19,2),
  cantidad_aprobada DECIMAL(19,4),
  valor_unitario_aprobado DECIMAL(19,2),
  valor_total_aprobado DECIMAL(19,2),
  estado VARCHAR(30) NOT NULL,
  observacion_presupuesto VARCHAR(2000),
  creado_por_id BIGINT NOT NULL,
  revisado_por_id BIGINT,
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  version BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  CONSTRAINT fk_necesidad_vigencia FOREIGN KEY (vigencia_id) REFERENCES vigencia(id),
  CONSTRAINT fk_necesidad_area FOREIGN KEY (area_id) REFERENCES area(id),
  CONSTRAINT fk_necesidad_rubro FOREIGN KEY (rubro_presupuestal_id) REFERENCES rubro_presupuestal(id),
  CONSTRAINT fk_necesidad_creador FOREIGN KEY (creado_por_id) REFERENCES usuario(id),
  CONSTRAINT fk_necesidad_revisor FOREIGN KEY (revisado_por_id) REFERENCES usuario(id),
  INDEX ix_necesidad_vigencia_area_estado (vigencia_id, area_id, estado),
  INDEX ix_necesidad_rubro (rubro_presupuestal_id)
);
CREATE TABLE distribucion_necesidad (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  necesidad_id BIGINT NOT NULL,
  servicio_id BIGINT NOT NULL,
  porcentaje DECIMAL(5,2) NOT NULL,
  valor_solicitado_distribuido DECIMAL(19,2) NOT NULL,
  valor_aprobado_distribuido DECIMAL(19,2) NOT NULL,
  CONSTRAINT fk_distribucion_necesidad FOREIGN KEY (necesidad_id) REFERENCES necesidad_presupuestal(id),
  CONSTRAINT fk_distribucion_servicio FOREIGN KEY (servicio_id) REFERENCES servicio(id),
  CONSTRAINT uq_distribucion_servicio UNIQUE (necesidad_id, servicio_id),
  INDEX ix_distribucion_servicio (servicio_id)
);
CREATE TABLE historial_necesidad (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  necesidad_id BIGINT NOT NULL,
  usuario_id BIGINT NOT NULL,
  accion VARCHAR(40) NOT NULL,
  descripcion VARCHAR(2000) NOT NULL,
  estado_anterior VARCHAR(30),
  estado_nuevo VARCHAR(30) NOT NULL,
  valor_solicitado DECIMAL(19,2) NOT NULL,
  valor_aprobado_anterior DECIMAL(19,2),
  valor_aprobado_nuevo DECIMAL(19,2),
  detalle_anterior TEXT,
  detalle_nuevo TEXT NOT NULL,
  fecha DATETIME(6) NOT NULL,
  CONSTRAINT fk_historial_necesidad FOREIGN KEY (necesidad_id) REFERENCES necesidad_presupuestal(id),
  CONSTRAINT fk_historial_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
  INDEX ix_historial_necesidad_fecha (necesidad_id, fecha)
);
